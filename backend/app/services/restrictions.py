"""Remove recipes a user must not see: allergies, allergen groups, blacklist.

Pure Python, like matching.py: no database or network access. The search
endpoint loads the user's restrictions and the ingredient hierarchy, then
calls filter_safe() BEFORE scoring. The same check is meant to be reused on
recipes generated by Gemini.

Safety rules (an allergy can hurt someone, so these lean cautious)
- Every recipe line is checked, including optional ingredients and staples.
- Allergy to a general ingredient blocks the specific ones:
  allergic to "beef" -> a recipe with "sirloin steak" is blocked.
- Allergy to a specific ingredient also blocks a recipe that only says the
  general one, because it might contain it:
  allergic to "sirloin steak" -> a recipe with "beef" is blocked.
- Siblings are not blocked: allergic to "flank steak" does not block
  "sirloin steak".
- An allergen group (dairy, tree nuts...) blocks every ingredient in the group,
  and every ingredient below a group member in the hierarchy.
- The blacklist is a preference, so it is looser: it blocks the ingredient and
  its specific children, but not a recipe that only names the general parent.
"""

from collections.abc import Collection, Mapping, Sequence
from dataclasses import dataclass, field

from app.services.matching import Candidate, RecipeLine, ancestors


@dataclass(frozen=True)
class Restrictions:
    """What one user must avoid. All values are ids from the database."""

    allergies: frozenset[int] = frozenset()  # ingredient ids
    blacklist: frozenset[int] = frozenset()  # ingredient ids
    allergen_groups: frozenset[int] = frozenset()  # allergen_group ids

    @property
    def is_empty(self) -> bool:
        return not (self.allergies or self.blacklist or self.allergen_groups)


@dataclass(frozen=True)
class Violation:
    ingredient_id: int
    name: str
    kind: str  # "allergy", "allergen_group" or "blacklist"
    reason: str


def _groups_of(
    ingredient_id: int,
    ancestor_ids: set[int],
    ingredient_groups: Mapping[int, Collection[int]],
) -> set[int]:
    """Allergen groups of an ingredient, including those inherited from above."""
    found = set(ingredient_groups.get(ingredient_id, ()))
    for ancestor_id in ancestor_ids:
        found |= set(ingredient_groups.get(ancestor_id, ()))
    return found


def find_violations(
    lines: Sequence[RecipeLine],
    restrictions: Restrictions,
    parents: Mapping[int, int | None],
    ingredient_groups: Mapping[int, Collection[int]] | None = None,
) -> list[Violation]:
    """Return every reason these recipe lines are not safe for the user.

    parents: ingredient_id -> parent_ingredient_id.
    ingredient_groups: ingredient_id -> allergen group ids it belongs to.
    An empty list means the recipe is safe.
    """
    if restrictions.is_empty:
        return []
    ingredient_groups = ingredient_groups or {}
    found: list[Violation] = []

    for line in lines:
        above = ancestors(line.ingredient_id, parents)

        if line.ingredient_id in restrictions.allergies:
            found.append(Violation(line.ingredient_id, line.name, "allergy",
                                   f"{line.name} is on the allergy list"))
        elif above & restrictions.allergies:
            found.append(Violation(line.ingredient_id, line.name, "allergy",
                                   f"{line.name} is a kind of an allergy ingredient"))
        elif any(line.ingredient_id in ancestors(a, parents)
                 for a in restrictions.allergies):
            found.append(Violation(line.ingredient_id, line.name, "allergy",
                                   f"{line.name} may contain an allergy ingredient"))

        shared = _groups_of(line.ingredient_id, above, ingredient_groups) \
            & restrictions.allergen_groups
        if shared:
            found.append(Violation(line.ingredient_id, line.name, "allergen_group",
                                   f"{line.name} is in an allergen group the user avoids"))

        if (line.ingredient_id in restrictions.blacklist
                or above & restrictions.blacklist):
            found.append(Violation(line.ingredient_id, line.name, "blacklist",
                                   f"{line.name} is on the blacklist"))

    return found


def is_safe(
    lines: Sequence[RecipeLine],
    restrictions: Restrictions,
    parents: Mapping[int, int | None],
    ingredient_groups: Mapping[int, Collection[int]] | None = None,
) -> bool:
    return not find_violations(lines, restrictions, parents, ingredient_groups)


def filter_safe(
    candidates: Sequence[Candidate],
    restrictions: Restrictions,
    parents: Mapping[int, int | None],
    ingredient_groups: Mapping[int, Collection[int]] | None = None,
) -> list[Candidate]:
    """Keep only recipes with no violations, in the original order."""
    return [
        c for c in candidates
        if is_safe(c.lines, restrictions, parents, ingredient_groups)
    ]